"""Generate `<project>/.immune/scenarios.py`: deterministic legitimate journeys for the `legit` gate.

No LLM: the plan is derived from the OpenAPI (every GET operation), `columns.yaml` (which table each path
parameter selects, and whether access is by owner or by group membership) and the manifest. The generated
module holds the plan as data and runs it with ``immune.legit`` (see there for what a journey does).

A GET operation is covered when every path parameter maps to something the user legitimately addresses
(its own rows, its groups, itself) and every required query parameter has legitimate values (enum or
pattern alternatives; a file name under the profile's allowed roots for a file-like parameter). Other
operations are listed in the generated module as uncovered: for them the gate reports "no coverage" and
autopatch stays capped at pr.
"""
from __future__ import annotations

import os
import pprint
import re

from immune.initsteps import openapi as oa

MODULE = "scenarios"
REL = ".immune/scenarios.py"
FILE_PARAM_RE = re.compile(r"(file|name|path|template|attachment|download|doc|asset|image|manual)", re.I)
BENIGN_TEXT = ["a", "de la"]          # letters and a space: never a SQL/path metacharacter


def _schema(doc, p) -> dict:
    s = oa._deref(doc, p.get("schema") or {})
    for alt in s.get("anyOf") or s.get("oneOf") or []:
        alt = oa._deref(doc, alt)
        if alt.get("type") and alt.get("type") != "null":
            return alt
    return s


def _alternatives(pattern: str) -> list | None:
    m = re.fullmatch(r"\^?\(?((?:[A-Za-z0-9_\-]+\|)*[A-Za-z0-9_\-]+)\)?\$?", pattern or "")
    return m.group(1).split("|") if m else None


def _query_spec(doc, p, op_path) -> dict | None:
    """-> {"name", "required", "values"} or None when no legitimate value is known for a required param."""
    s = _schema(doc, p)
    name, required = p.get("name"), bool(p.get("required"))
    if p.get("x-sensitive") or s.get("x-sensitive"):
        return None if required else {"name": name, "required": False, "values": []}
    vals = None
    if isinstance(s.get("enum"), list):
        vals = [v for v in s["enum"] if isinstance(v, (str, int))]
    elif s.get("pattern") and _alternatives(s["pattern"]):
        vals = _alternatives(s["pattern"])
    elif s.get("type") in ("integer", "number", "boolean"):
        vals = [] if not required else None
    elif s.get("type", "string") == "string":
        if required and FILE_PARAM_RE.search(name or "") or required and FILE_PARAM_RE.search(op_path):
            vals = "files"
        elif not required:
            vals = list(BENIGN_TEXT)
    if vals is None:
        return None
    return {"name": name, "required": required, "values": vals}


def _path_source(param: str, cols: dict) -> dict | None:
    r = (cols.get("routes") or {}).get(param)
    if not isinstance(r, dict):
        return None
    ut, uc = cols.get("users_table"), cols.get("user_id_column") or "id"
    if r.get("access") == "members":
        return {"group": r["table"]}
    if r.get("table") == ut and r.get("column") == uc:
        return {"self": True}
    spec = (cols.get("tables") or {}).get(r.get("table")) or {}
    if isinstance(spec, dict) and spec.get("owner"):
        return {"own": r["table"]}
    return None


def build_plan(doc: dict, cols: dict, profile_module: str) -> dict:
    ops, uncovered = [], []
    for o in oa.operations(doc or {}):
        if o["method"] != "GET":
            continue
        why = None
        pp = {}
        for p in o["path_params"]:
            src = _path_source(p, cols)
            if src is None:
                why = "path parameter %s selects nothing a user owns or belongs to (columns.yaml routes)" % p
                break
            pp[p] = src
        query = []
        if why is None:
            for p in o["params"]:
                if p.get("in") != "query":
                    continue
                q = _query_spec(doc, p, o["path"])
                if q is None:
                    why = "no legitimate value known for the required query parameter %s" % p.get("name")
                    break
                if q["values"] or q["required"]:
                    query.append(q)
        if why:
            uncovered.append({"op": o["key"], "why": why})
            continue
        ops.append({"path": o["path"], "path_params": pp, "query": query, "admin": not o["path_params"]})
    return {"profile": profile_module, "users_table": cols.get("users_table"), "ops": ops, "uncovered": uncovered}


def render(plan: dict, name: str) -> str:
    return ('"""Legitimate journeys of %s for the `legit` gate (generated by `immune init`; deterministic, no LLM).\n\n'
            "An existing seeded user reads its own resources on every GET route listed in PLAN; parameter-free routes\n"
            "are also read by the admin. Runtime: immune.legit. Regenerate with `immune init`; edit PLAN to add\n"
            "values. Operations in PLAN['uncovered'] have no journey (the legit gate caps autopatch at pr for them).\n"
            '"""\n'
            "from immune.legit import scenarios_from\n\n"
            "PARTIAL_COVERAGE = True   # GET routes only: other routes count as 'no coverage', never as covered\n"
            "PLAN = %s\n\n"
            "SCENARIOS = scenarios_from(PLAN)\n") % (name, pprint.pformat(plan, width=110, sort_dicts=True))


def write(project: str, doc: dict, cols: dict, profile_module: str, name: str) -> dict:
    plan = build_plan(doc, cols, profile_module)
    path = os.path.join(project, REL)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(render(plan, name))
    return plan
