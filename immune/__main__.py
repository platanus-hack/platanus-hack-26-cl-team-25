class CliError(Exception):
    pass


def say(msg: str) -> None:
    print(msg, flush=True)


def python() -> str:
    venv = os.path.join(HOME, ".venv", "bin", "python")
    return venv if os.path.exists(venv) else sys.executable


# ---------------------------------------------------------------------------- env / secrets
def _env_file(path: str) -> dict:
    out = {}
    try:
        with open(path) as f:
            for line in f:
                line = line.strip()
                if line and not line.startswith("#") and "=" in line:
                    k, v = line.split("=", 1)
                    out[k.strip()] = v.strip()
    except OSError:
        pass
    return out


def stack_secrets(cfg: icfg.Config) -> dict:
    """Demo: deploy/demo.env. Other projects: <runtime>/secrets.env, generated once (0600)."""
    if os.path.realpath(cfg.project_dir) == os.path.realpath(HOME):
        vals = {k: v for k, v in _env_file(DEMO_ENV).items() if k in SECRET_KEYS}
    else:
        path = cfg.rt("secrets.env")
        vals = _env_file(path)
        if any(k not in vals for k in SECRET_KEYS):
            for k in SECRET_KEYS:
                vals.setdefault(k, pysecrets.token_hex(16))
            os.makedirs(cfg.runtime_dir, exist_ok=True)
            fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
            with os.fdopen(fd, "w") as f:
                f.write("# generated by `immune up`; secrets of this stack\n")
                f.writelines("%s=%s\n" % (k, vals[k]) for k in SECRET_KEYS)
    for k in SECRET_KEYS:
        if os.environ.get(k):
            vals[k] = os.environ[k]
    if cfg.auth.kind == "jwt-hs256":
        v = os.environ.get(cfg.auth.secret_env) or _env_file(cfg.rt("secrets.env")).get(cfg.auth.secret_env)
        if not v:
            raise CliError("auth.kind jwt-hs256: export %s (the HS256 secret prod tokens are signed with)"
                           % cfg.auth.secret_env)
        vals[cfg.auth.secret_env] = v
    missing = [k for k in SECRET_KEYS if not vals.get(k)]
    if missing:
        raise CliError("missing secrets: %s" % ", ".join(missing))
    return vals


def write_stack_env(cfg: icfg.Config, sec: dict) -> str:
    """The env_file of the compose services (in-container values)."""
    d = cfg.rt("stack")
    os.makedirs(d, exist_ok=True)
    path = os.path.join(d, "containers.env")
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write("# written by `immune up`\n")
        for k, v in sec.items():
            f.write("%s=%s\n" % (k, v))
        f.write("BUS_URL=http://dashboard:8090\n")
    return path


def compose_env(cfg: icfg.Config, sec_file: str, run_id: str) -> dict:
    env = dict(os.environ)
    env.update({
        "IMMUNE_NAME": cfg.name, "IMMUNE_HOME": HOME, "IMMUNE_RUNTIME": cfg.runtime_dir,
        "IMMUNE_OPENAPI": cfg.openapi, "IMMUNE_SECRETS_FILE": sec_file, "RUN_ID": run_id,
        "IMMUNE_APP_PORT": str(cfg.app.port), "IMMUNE_MODE": cfg.mode,
        "IMMUNE_AUTH": json.dumps(cfg.auth.to_dict(), separators=(",", ":")),
        "IMMUNE_PORT_GATEWAY": str(cfg.ports["gateway"]), "IMMUNE_PORT_ADMIN": str(cfg.ports["admin"]),
        "IMMUNE_PORT_DASHBOARD": str(cfg.ports["dashboard"]),
        "IMMUNE_UID": str(os.getuid()), "IMMUNE_GID": str(os.getgid()),
    })
    return env


def host_env(cfg: icfg.Config, sec: dict, run_id: str) -> dict:
    env = dict(os.environ)
    env.update(sec)
    env.update({
        "IMMUNE_PROJECT": cfg.project_dir, "RUNTIME_DIR": cfg.runtime_dir, "REPO_DIR": HOME, "RUN_ID": run_id,
        "PYTHONPATH": HOME, "FLEET_PORT": str(cfg.ports["fleet"]),
        "GATEWAY_ADMIN_URL": "http://127.0.0.1:%d" % cfg.ports["admin"],
        "GATEWAY_URL": "http://127.0.0.1:%d" % cfg.ports["gateway"],
        "FLEET_URL": "http://127.0.0.1:%d" % cfg.ports["fleet"],
        "FLEET_BUS_URL": "http://127.0.0.1:%d" % cfg.ports["dashboard"],
        "PIPELINE_BUS_URL": "http://127.0.0.1:%d" % cfg.ports["dashboard"],
    })
    env.pop("BUS_URL", None)
    return env


# ---------------------------------------------------------------------------- docker helpers
def docker(*args, check=True, env=None, timeout=300) -> str:
    p = subprocess.run(["docker", *args], capture_output=True, text=True, env=env, timeout=timeout)
    if check and p.returncode != 0:
        raise CliError("docker %s: %s" % (" ".join(args[:3]), (p.stderr or p.stdout).strip()[-800:]))
    return p.stdout


def compose(cfg, env, *args, check=True, timeout=300) -> str:
    return docker("compose", "-p", cfg.compose_project, "-f", COMPOSE, *args, check=check, env=env, timeout=timeout)


def remove_owned(cfg: icfg.Config) -> int:
    """Containers fleet/compose created for this project (label immune.project=<name>)."""
    ids = docker("ps", "-aq", "--filter", "label=immune.project=%s" % cfg.name, check=False).split()
    # fleet containers from before the project label existed: named immune-<name>-* and run-labelled
    for line in docker("ps", "-a", "--filter", "label=immune.run", "--format", "{{.ID}} {{.Names}}",
                       check=False).splitlines():
        cid, _, name = line.partition(" ")
        if name.startswith(cfg.prefix + "-") and cid not in ids:
            ids.append(cid)
    if ids:
        docker("rm", "-f", *ids, check=False)
    return len(ids)


# ---------------------------------------------------------------------------- host processes
def _pidfile(cfg, name):
    return cfg.rt("logs", name + ".pid")


def _alive(pid: int) -> bool:
    try:
        os.kill(pid, 0)
        return True
    except (OSError, ValueError):
        return False


def start_host(cfg, name: str, module: str, env: dict) -> None:
    pf = _pidfile(cfg, name)
    try:
        if _alive(int(open(pf).read().strip())):
            return
    except (OSError, ValueError):
        pass
    os.makedirs(cfg.rt("logs"), exist_ok=True)
    log = open(cfg.rt("logs", name + ".log"), "wb")
    p = subprocess.Popen([python(), "-m", module], cwd=HOME, env=env, stdout=log, stderr=subprocess.STDOUT,
                         stdin=subprocess.DEVNULL, start_new_session=True)
    with open(pf, "w") as f:
        f.write(str(p.pid))


def stop_host(cfg) -> None:
    d = cfg.rt("logs")
    if not os.path.isdir(d):
        return
    pids = []
    for fn in os.listdir(d):
        if fn.endswith(".pid"):
            try:
                pid = int(open(os.path.join(d, fn)).read().strip())
                os.kill(pid, signal.SIGTERM)
                pids.append(pid)
            except (OSError, ValueError):
                pass
            try:
                os.remove(os.path.join(d, fn))
            except OSError:
                pass
    deadline = time.time() + 10
    while pids and time.time() < deadline:
        pids = [p for p in pids if _alive(p)]
        time.sleep(0.2)
    for p in pids:
        try:
            os.kill(p, signal.SIGKILL)
        except OSError:
            pass


# ---------------------------------------------------------------------------- http
def http(method: str, url: str, body=None, token: str = "", timeout: float = 5.0):
    data = json.dumps(body).encode() if body is not None else None
    req = urllib.request.Request(url, data=data, method=method)
    req.add_header("content-type", "application/json")
    if token:
        req.add_header("x-admin-token", token)
    with urllib.request.urlopen(req, timeout=timeout) as r:
        raw = r.read()
    return json.loads(raw) if raw else {}


def wait_url(url: str, token: str = "", tries: int = 60) -> None:
    for _ in range(tries):
        try:
            http("GET", url, token=token, timeout=2)
            return
        except Exception:  # noqa: BLE001
            time.sleep(0.5)
    raise CliError("timeout waiting for %s" % url)


# ---------------------------------------------------------------------------- seed + release
def build_release(cfg: icfg.Config, dest: str, ref: str | None = None) -> None:
    """A full copy of app.release_paths (working tree, or `git archive <ref>` when ref is set)."""
    if os.path.exists(dest):
        shutil.rmtree(dest)
    os.makedirs(dest)
    if ref:
        raw = subprocess.run(["git", "-C", cfg.project_dir, "archive", "--format=tar", ref, "--",
                              *cfg.app.release_paths], capture_output=True, timeout=120)
        if raw.returncode != 0:
            raise CliError("git archive %s: %s" % (ref, raw.stderr.decode()[-300:]))
        from pipeline.repo import safe_extract
        with tarfile.open(fileobj=io.BytesIO(raw.stdout)) as tf:
            safe_extract(tf, dest, prefix=cfg.app.release_paths)
        return
    for p in cfg.app.release_paths:
        src, dst = os.path.join(cfg.project_dir, p), os.path.join(dest, p)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        if os.path.isdir(src):
            shutil.copytree(src, dst, ignore=IGNORE, symlinks=True)
        else:
            shutil.copy2(src, dst, follow_symlinks=False)


def _under(path: str, root: str) -> bool:
    path, root = os.path.realpath(path), os.path.realpath(root)
    return path == root or path.startswith(root + os.sep)


def seed(cfg: icfg.Config) -> str:
    """Fresh t0: data, recordings, bus, releases/t0, run_id. -> run id."""
    rt = cfg.runtime_dir
    for d in ("data", "recordings", "bus", "releases", "pipeline"):   # pipeline: incident state belongs to the run
        target = os.path.join(rt, d)
        if d == "data" and not _under(cfg.data.prod_db, target) and os.path.isdir(target):
            # the live database is not ours to wipe: keep it, rebuild everything else under data/
            for x in os.listdir(target):
                full = os.path.join(target, x)
                if not _under(cfg.data.prod_db, full):
                    shutil.rmtree(full) if os.path.isdir(full) else os.remove(full)
            continue
        shutil.rmtree(target, ignore_errors=True)
    for d in ("data/shadow", "recordings", "bus", "releases", "logs"):
        os.makedirs(os.path.join(rt, d), exist_ok=True)
    os.makedirs(cfg.prod_data_dir, exist_ok=True)
    shadow_markers = os.path.join(cfg.shadow_dir, "markers.json")
    if cfg.data.seed_command:
        prod_db = cfg.data.prod_db
        tmp_prod = None
        if not _under(prod_db, rt) and os.path.exists(prod_db):
            tmp_prod = os.path.join(rt, "data", ".seed-prod-discarded.db")   # never overwrite a live database
            prod_db = tmp_prod
        line = cfg.seed_command_for(prod_db=prod_db, shadow_db=cfg.shadow_seed, manifest=cfg.manifest_path,
                                    markers=shadow_markers, seed=1)
        env = dict(os.environ, PYTHONPATH=os.pathsep.join([cfg.project_dir, HOME]),
                   PATH=os.path.dirname(python()) + os.pathsep + os.environ.get("PATH", ""))
        p = subprocess.run(["/bin/sh", "-c", line], cwd=cfg.project_dir, env=env, capture_output=True, text=True,
                           timeout=300)
        if p.returncode != 0:
            raise CliError("data.seed_command failed (exit %d): %s" % (p.returncode, (p.stderr or p.stdout)[-800:]))
        if tmp_prod:
            os.remove(tmp_prod)
    else:
        try:
            shadowdata = importlib.import_module("immune.shadowdata")
        except ModuleNotFoundError as e:
            if e.name != "immune.shadowdata":
                raise
            raise CliError("no data.seed_command and immune.shadowdata is not installed") from None
        shadowdata.build(cfg)
    if os.path.isfile(shadow_markers):
        shutil.copyfile(shadow_markers, cfg.markers_path)
    build_release(cfg, cfg.release_dir("t0"), os.environ.get("T0_REF") or None)
    run_id = time.strftime("%m%d-%H%M%S")
    with open(os.path.join(rt, "run_id"), "w") as f:
        f.write(run_id + "\n")
    return run_id


# ---------------------------------------------------------------------------- commands
def cmd_up(cfg: icfg.Config, reset: bool) -> int:
    sec = stack_secrets(cfg)
    stop_host(cfg)
    remove_owned(cfg)
    sec_file = write_stack_env(cfg, sec)
    if reset:
        compose(cfg, compose_env(cfg, sec_file, "dev"), "down", "--remove-orphans", check=False)
    run_id = seed(cfg)
    say("seeded t0 (run %s)" % run_id)
    cenv = compose_env(cfg, sec_file, run_id)
    compose(cfg, cenv, "up", "-d", "--force-recreate")
    tok = sec["ADMIN_TOKEN"]
    wait_url("http://127.0.0.1:%d/health" % cfg.ports["dashboard"])
    wait_url("http://127.0.0.1:%d/_admin/health" % cfg.ports["admin"], tok)
    henv = host_env(cfg, sec, run_id)
    start_host(cfg, "fleet", "fleet", henv)
    wait_url("http://127.0.0.1:%d/state" % cfg.ports["fleet"], tok)
    res = http("POST", "http://127.0.0.1:%d/reset" % cfg.ports["fleet"],
               {"release": "t0", "pool_size": int(os.environ.get("POOL_SIZE") or cfg.pool_size)}, tok, timeout=180)
    say(json.dumps(res))
    if cfg.mode != "enforce":
        http("POST", "http://127.0.0.1:%d/_admin/mode" % cfg.ports["admin"], {"mode": cfg.mode}, tok)
    if not os.environ.get("NO_PIPELINE"):
        start_host(cfg, "pipeline", "pipeline", henv)
    eff, why = cfg.effective_autopatch()
    say("stack immune-%s up: gateway http://127.0.0.1:%d  dashboard http://127.0.0.1:%d  mode=%s autopatch=%s%s"
        % (cfg.name, cfg.ports["gateway"], cfg.ports["dashboard"], cfg.mode, eff,
           (" (%s)" % "; ".join(why)) if why else ""))
    return 0


def cmd_down(cfg: icfg.Config) -> int:
    stop_host(cfg)
    remove_owned(cfg)
    sec_file = cfg.rt("stack", "containers.env")
    if not os.path.isfile(sec_file):
        sec_file = DEMO_ENV
    compose(cfg, compose_env(cfg, sec_file, "dev"), "down", "--remove-orphans", check=False)
    remove_owned(cfg)
    say("stack immune-%s down" % cfg.name)
    return 0


def cmd_status(cfg: icfg.Config) -> int:
    say(docker("ps", "--format", "table {{.Names}}\t{{.Status}}", "--filter",
               "label=immune.project=%s" % cfg.name, check=False).rstrip())
    for name in ("fleet", "pipeline"):
        try:
            pid = int(open(_pidfile(cfg, name)).read().strip())
            say("%-9s pid %d %s" % (name, pid, "running" if _alive(pid) else "DEAD"))
        except (OSError, ValueError):
            say("%-9s not running" % name)
    try:
        tok = stack_secrets(cfg)["ADMIN_TOKEN"]
        say(json.dumps(http("GET", "http://127.0.0.1:%d/state" % cfg.ports["fleet"], token=tok, timeout=3)))
    except Exception as e:  # noqa: BLE001
        say("fleet: unreachable (%s)" % e)
    return 0


def _events(cfg) -> list:
    out = []
    try:
        with open(cfg.rt("bus", "events.jsonl"), encoding="utf-8") as f:
            for line in f:
                try:
                    e = json.loads(line)
                except ValueError:
                    continue
                if isinstance(e, dict):
                    out.append(e)
    except OSError:
        pass
    return out


def report(cfg: icfg.Config) -> dict:
    evs = _events(cfg)
    types = Counter(e.get("type") for e in evs)
    routed = [e.get("data") or {} for e in evs if e.get("type") == "request.routed"]
    verdicts = Counter(d.get("verdict") for d in routed if d.get("verdict"))
    routes = Counter(d.get("route") for d in routed)
    would = Counter(d.get("would_route") for d in routed if d.get("observe"))
    classes = Counter((e.get("data") or {}).get("class") for e in evs if e.get("type") == "request.classified")
    oracles = Counter()
    for e in evs:
        if e.get("type") == "oracle.fired":
            for x in (e.get("data") or {}).get("events") or []:
                oracles[x.get("oracle")] += 1
    incidents = {}
    for e in evs:
        d = e.get("data") or {}
        iid = d.get("incident") or e.get("incident")
        if not iid:
            continue
        inc = incidents.setdefault(iid, {"incident": iid})
        if e.get("type") == "incident.opened":
            inc.update({k: d.get(k) for k in ("vuln_class", "method", "route")})
        elif e.get("type") == "incident.closed":
            inc.update({k: d.get(k) for k in ("outcome", "outcome_detail", "seconds_to_rule", "seconds_to_patch")})
        elif e.get("type") == "verify.result":
            inc["exploit_blocked_on_prod"] = d.get("exploit_blocked_on_prod")
    return {"project": cfg.name, "mode": cfg.mode, "events": len(evs), "requests": len(routed),
            "classes": dict(classes), "routes": dict(routes), "detonations": sum(verdicts.values()),
            "verdicts": dict(verdicts), "oracles": dict(oracles), "oracle_fired": types.get("oracle.fired", 0),
            "would_have": dict(would), "incidents": list(incidents.values())}


def cmd_report(cfg: icfg.Config, as_json: bool) -> int:
    r = report(cfg)
    if as_json:
        say(json.dumps(r, indent=1))
        return 0
    say("project %s (mode %s): %d events, %d requests" % (r["project"], r["mode"], r["events"], r["requests"]))
    say("  classified: %s" % (", ".join("%s=%d" % kv for kv in sorted(r["classes"].items(), key=str)) or "-"))
    say("  routed:     %s" % (", ".join("%s=%d" % kv for kv in sorted(r["routes"].items(), key=str)) or "-"))
    say("  detonations: %d (%s)" % (r["detonations"], ", ".join("%s=%d" % kv for kv in r["verdicts"].items()) or "-"))
    say("  oracle.fired: %d (%s)" % (r["oracle_fired"], ", ".join("%s=%d" % kv for kv in r["oracles"].items()) or "-"))
    if r["would_have"]:
        say("  observe mode, enforce would have routed: %s" % ", ".join(
            "%s=%d" % kv for kv in sorted(r["would_have"].items(), key=str)))
        n = sum(v for k, v in r["would_have"].items() if k not in ("prod", None))
        say("  -> %d request(s) would have been denied or diverted to a shadow clone" % n)
    say("  incidents: %d" % len(r["incidents"]))
    for i in r["incidents"]:
        say("    %s %s %s %s -> %s%s (rule %ss, patch %ss)%s" % (
            i["incident"], i.get("vuln_class"), i.get("method"), i.get("route"), i.get("outcome") or "open",
            "/" + i["outcome_detail"] if i.get("outcome_detail") else "", i.get("seconds_to_rule"),
            i.get("seconds_to_patch"),
            "" if i.get("exploit_blocked_on_prod") is None else " blocked_on_prod=%s" % i["exploit_blocked_on_prod"]))
    return 0


def cmd_set(cfg: icfg.Config, key: str, value: str) -> int:
    path = icfg.set_key(cfg.project_dir, key, value)
    say("%s: %s = %s" % (path, key, value))
    if key == "mode":
        try:
            tok = stack_secrets(cfg)["ADMIN_TOKEN"]
            http("POST", "http://127.0.0.1:%d/_admin/mode" % cfg.ports["admin"], {"mode": value}, tok, timeout=3)
            say("gateway switched to %s" % value)
        except (urllib.error.URLError, OSError, CliError) as e:
            say("gateway not reachable (%s); applies on the next `immune up`" % getattr(e, "reason", e))
    if key == "autopatch":
        eff, why = icfg.load(cfg.project_dir).effective_autopatch()
        if eff != value:
            say("effective autopatch: %s (%s)" % (eff, "; ".join(why)))
        say("the pipeline reads it at the start of each incident")
    return 0


def dispatch(cmd: str, argv: list) -> int:
    if cmd == "anticipate":
        try:
            import runpy
            sys.argv = ["immune anticipate"] + argv
            runpy.run_module("anticipate", run_name="__main__", alter_sys=True)
            return 0
        except ModuleNotFoundError as e:
            if e.name == "anticipate":
                say("immune anticipate: not installed (package anticipate missing)")
                return 2
            raise
        except SystemExit as e:
            return int(e.code or 0) if not isinstance(e.code, str) else 1
    mod = DISPATCH[cmd]
    try:
        m = importlib.import_module(mod)
    except ModuleNotFoundError as e:
        if e.name == mod:
            say("immune %s: not installed (module %s is missing)" % (cmd, mod))
            return 2
        raise
    main = getattr(m, "main", None)
    if main is None:
        say("immune %s: not installed (%s has no main())" % (cmd, mod))
        return 2
    return int(main(argv) or 0)


def main(argv=None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    i = 0
    while i < len(argv) and argv[i].startswith("-"):   # skip leading options (and the value of --project)
        i += 2 if argv[i] == "--project" else 1
    if i < len(argv) and argv[i] in list(DISPATCH) + ["anticipate"]:
        return dispatch(argv[i], argv[:i] + argv[i + 1:])
    ap = argparse.ArgumentParser(prog="immune", description="immune: protect a web app (contracts/product.md)")
    ap.add_argument("--project", default=None, help="project dir (default: nearest .immune/ upward, else IMMUNE_HOME)")
    sub = ap.add_subparsers(dest="cmd", required=True)
    for c in ("up", "down", "status", "reset"):
        p = sub.add_parser(c)
        p.add_argument("--project", default=argparse.SUPPRESS)
    p = sub.add_parser("report")
    p.add_argument("--project", default=argparse.SUPPRESS)
    p.add_argument("--json", action="store_true")
    p = sub.add_parser("mode")
    p.add_argument("value", choices=icfg.MODES)
    p.add_argument("--project", default=argparse.SUPPRESS)
    p = sub.add_parser("autopatch")
    p.add_argument("value", choices=icfg.AUTOPATCH)
    p.add_argument("--project", default=argparse.SUPPRESS)
    for c in list(DISPATCH) + ["anticipate"]:
        sub.add_parser(c, add_help=False)
    a = ap.parse_args(argv)
    project = a.project or os.environ.get("IMMUNE_PROJECT") or icfg.find_project()
    try:
        cfg = icfg.load(project)
        os.environ["IMMUNE_PROJECT"] = cfg.project_dir
        icfg.reset_cache()
        if a.cmd in ("up", "reset"):
            return cmd_up(cfg, reset=a.cmd == "reset")
        if a.cmd == "down":
            return cmd_down(cfg)
        if a.cmd == "status":
            return cmd_status(cfg)
        if a.cmd == "report":
            return cmd_report(cfg, a.json)
        if a.cmd in ("mode", "autopatch"):
            return cmd_set(cfg, a.cmd, a.value)
    except icfg.ConfigError as e:
        print("immune: %s" % e, file=sys.stderr)
        return 2
    except CliError as e:
        print("immune %s: %s" % (a.cmd, e), file=sys.stderr)
        return 1
    return 2


if __name__ == "__main__":
    sys.exit(main())
