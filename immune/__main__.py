# ---------------------------------------------------------------------------- env / secrets
def _env_file(path: str) -> dict:
    out = {}
    try:
        with open(path) as f:
            for line in f:
                line = line.strip()
                if line and not line.startswith("#") and "=" in line:
                    k, v = line.split("=", 1)
                    out[k.strip()] = v.strip()
    except OSError:
        pass
    return out


def stack_secrets(cfg: icfg.Config) -> dict:
    """<runtime>/secrets.env, random per machine, generated once (0600). Every project, the built-in demo too.

    When the file is missing or incomplete and a stack is running, the values its containers were started with
    (<runtime>/stack/containers.env) are kept, so the running stack stays reachable.
    """
    path = cfg.rt("secrets.env")
    vals = _env_file(path)
    if any(k not in vals for k in SECRET_KEYS):
        running = _env_file(cfg.rt("stack", "containers.env"))
        for k in SECRET_KEYS:
            vals.setdefault(k, running.get(k) or pysecrets.token_hex(16))
        os.makedirs(cfg.runtime_dir, exist_ok=True)
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "w") as f:
            f.write("# generated by `immune up`; secrets of this stack\n")
            f.writelines("%s=%s\n" % (k, vals[k]) for k in SECRET_KEYS)
    for k in SECRET_KEYS:
        if os.environ.get(k):
            vals[k] = os.environ[k]
    if cfg.auth.kind == "jwt-hs256":
        v = os.environ.get(cfg.auth.secret_env) or _env_file(cfg.rt("secrets.env")).get(cfg.auth.secret_env)
        if not v:
            raise CliError("auth.kind jwt-hs256: export %s (the HS256 secret prod tokens are signed with)"
                           % cfg.auth.secret_env)
        vals[cfg.auth.secret_env] = v
    missing = [k for k in SECRET_KEYS if not vals.get(k)]
    if missing:
        raise CliError("missing secrets: %s" % ", ".join(missing))
    return vals


def write_stack_env(cfg: icfg.Config, sec: dict) -> str:
    """The env_file of the compose services (in-container values)."""
    d = cfg.rt("stack")
    os.makedirs(d, exist_ok=True)
    path = os.path.join(d, "containers.env")
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write("# written by `immune up`\n")
        for k, v in sec.items():
            f.write("%s=%s\n" % (k, v))
        f.write("BUS_URL=http://dashboard:8090\n")
    return path


