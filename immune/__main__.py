def existing_run(cfg: icfg.Config) -> str | None:
    """The run id of a stack that can be resumed: seeded, with the fleet's record of what is in production."""
    try:
        run_id = open(cfg.rt("run_id")).read().strip()
        with open(cfg.rt("stack", "fleet-state.json")) as f:
            st = json.load(f)
    except (OSError, ValueError):
        return None
    if not run_id or not isinstance(st, dict) or st.get("run_id") != run_id or not st.get("release"):
        return None
    if not os.path.isdir(cfg.release_dir(str(st["release"]))):
        return None
    if cfg.app.runtime == "generic":
        # `immune down` removes this runtime's app images and demo database: resume only a stack still standing
        if not docker("ps", "-aq", "--filter", "label=immune.project=%s" % cfg.name, "--filter",
                      "label=immune.role=prod", check=False).split():
            return None
    return run_id


def check_ports(cfg: icfg.Config, names) -> None:
    """Fail with the port and the config key when something else already listens there. Call it only for
    ports this stack does not hold itself at that moment."""
    import socket
    busy = []
    for n in names:
        s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        s.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        try:
            s.bind(("127.0.0.1", int(cfg.ports[n])))
        except OSError:
            busy.append("%d (ports.%s)" % (cfg.ports[n], n))
        finally:
            s.close()
    if busy:
        raise CliError("port%s %s already in use on 127.0.0.1 by something that is not this stack. Free %s or set "
                       "other values under `ports:` in %s" % ("s" if len(busy) > 1 else "", ", ".join(busy),
                                                             "them" if len(busy) > 1 else "it",
                                                             os.path.join(cfg.dot_immune, "config.yaml")))


def services_running(cfg: icfg.Config) -> set:
    out = docker("ps", "--format", "{{.Names}}", "--filter", "label=immune.project=%s" % cfg.name, check=False)
    return {n[len(cfg.prefix) + 1:] for n in out.split() if n.startswith(cfg.prefix + "-")}


def wait_fleet(cfg, tok: str, timeout: float = 180.0) -> dict:
    """Block until the fleet has taken over the run (prod serving). -> its /state."""
    url = "http://127.0.0.1:%d/state" % cfg.ports["fleet"]
    deadline, st = time.time() + timeout, {}
    while time.time() < deadline:
        try:
            st = http("GET", url, token=tok, timeout=3)
            if st.get("ready") and (st.get("prod") or {}).get("active"):
                if len(st.get("clones") or []) >= int(st.get("pool_size") or 0) and st.get("gateway_ok"):
                    return st
            elif st.get("ready"):
                break
        except Exception:  # noqa: BLE001
            pass
        time.sleep(0.5)
    if (st.get("prod") or {}).get("active"):
        say("warning: production is serving but the clone pool is at %d/%s; suspicious requests are held back "
            "until it fills (see %s)" % (len(st.get("clones") or []), st.get("pool_size"), cfg.rt("logs", "fleet.log")))
        return st
    raise CliError("the fleet could not take over the existing run (state: %s); see %s, or start from t0 with "
                   "`immune reset`" % (json.dumps(st.get("prod")), cfg.rt("logs", "fleet.log")))


def cmd_resume(cfg: icfg.Config, sec: dict, run_id: str) -> int:
    """`immune up` on a stack that already ran: bring back whatever is missing, keep the release that is in
    production, the containment rules and the open incidents. Never goes back to t0 (that is `immune reset`)."""
    sec_file = write_stack_env(cfg, sec)
    up = services_running(cfg)
    check_ports(cfg, [n for n in ("gateway", "admin") if "gateway" not in up]
                + [n for n in ("dashboard",) if "dashboard" not in up]
                + [n for n in ("fleet",) if not host_pids(cfg, "fleet")[0]])
    compose(cfg, compose_env(cfg, sec_file, run_id), "up", "-d")
    tok = sec["ADMIN_TOKEN"]
    wait_url("http://127.0.0.1:%d/health" % cfg.ports["dashboard"])
    wait_url("http://127.0.0.1:%d/_admin/health" % cfg.ports["admin"], tok)
    henv = host_env(cfg, sec, run_id)
    start_host(cfg, "fleet", "fleet", henv)
    st = wait_fleet(cfg, tok)
    if not os.environ.get("NO_PIPELINE"):
        start_host(cfg, "pipeline", "pipeline", henv)
    eff, why = cfg.effective_autopatch()
    say("stack immune-%s resumed (run %s, release %s in production, %d clone(s)): gateway http://127.0.0.1:%d  "
        "dashboard http://127.0.0.1:%d  autopatch=%s%s"
        % (cfg.name, run_id, st["prod"]["release"], len(st.get("clones") or []), cfg.ports["gateway"],
           cfg.ports["dashboard"], eff, (" (%s)" % "; ".join(why)) if why else ""))
    return 0


def cmd_up(cfg: icfg.Config, reset: bool) -> int:
    if not reset:
        run_id = existing_run(cfg)
        if run_id:
            return cmd_resume(cfg, stack_secrets(cfg), run_id)
    if cfg.app.runtime == "generic":      # any-language app in its own image (immune/generic.py)
        from . import generic
        return generic.cmd_up(cfg, reset)
    sec = stack_secrets(cfg)
    stop_host(cfg)
    remove_owned(cfg)
    sec_file = write_stack_env(cfg, sec)
    compose(cfg, compose_env(cfg, sec_file, "dev"), "down", "--remove-orphans", check=False)
    check_ports(cfg, ("gateway", "admin", "dashboard", "fleet"))
    run_id = seed(cfg)
    say("seeded t0 (run %s)" % run_id)
    cenv = compose_env(cfg, sec_file, run_id)
    compose(cfg, cenv, "up", "-d", "--force-recreate")
    tok = sec["ADMIN_TOKEN"]
    wait_url("http://127.0.0.1:%d/health" % cfg.ports["dashboard"])
    wait_url("http://127.0.0.1:%d/_admin/health" % cfg.ports["admin"], tok)
    henv = host_env(cfg, sec, run_id)
    start_host(cfg, "fleet", "fleet", henv)
    wait_url("http://127.0.0.1:%d/state" % cfg.ports["fleet"], tok)
    res = http("POST", "http://127.0.0.1:%d/reset" % cfg.ports["fleet"],
               {"release": "t0", "pool_size": int(os.environ.get("POOL_SIZE") or cfg.pool_size)}, tok, timeout=180)
    say(json.dumps(res))
    if cfg.mode != "enforce":
        http("POST", "http://127.0.0.1:%d/_admin/mode" % cfg.ports["admin"], {"mode": cfg.mode}, tok)
    if not os.environ.get("NO_PIPELINE"):
        start_host(cfg, "pipeline", "pipeline", henv)
    eff, why = cfg.effective_autopatch()
    say("stack immune-%s up: gateway http://127.0.0.1:%d  dashboard http://127.0.0.1:%d  mode=%s autopatch=%s%s"
        % (cfg.name, cfg.ports["gateway"], cfg.ports["dashboard"], cfg.mode, eff,
           (" (%s)" % "; ".join(why)) if why else ""))
    return 0


def cmd_down(cfg: icfg.Config) -> int:
    if cfg.app.runtime == "generic":
        from . import generic
        return generic.cmd_down(cfg)
    stop_host(cfg)
    remove_owned(cfg)
    sec_file = cfg.rt("stack", "containers.env")
    if not os.path.isfile(sec_file):
        sec_file = DEMO_ENV
    compose(cfg, compose_env(cfg, sec_file, "dev"), "down", "--remove-orphans", check=False)
    remove_owned(cfg)
    say("stack immune-%s down" % cfg.name)
    return 0


def cmd_status(cfg: icfg.Config) -> int:
    say(docker("ps", "--format", "table {{.Names}}\t{{.Status}}", "--filter",
               "label=immune.project=%s" % cfg.name, check=False).rstrip())
    problems = []
    for name in ("fleet", "pipeline"):
        sup, child = host_pids(cfg, name)
        if sup and child:
            say("%-9s running (pid %d, supervisor %d)" % (name, child, sup))
        elif sup:
            say("%-9s RESTARTING (supervisor %d; see %s)" % (name, sup, cfg.rt("logs", name + ".log")))
            problems.append(name + " is restarting")
        else:
            say("%-9s NOT RUNNING" % name)
            if not (name == "pipeline" and os.environ.get("NO_PIPELINE")):
                problems.append(name + " is not running")
    try:
        tok = stack_secrets(cfg)["ADMIN_TOKEN"]
    except CliError as e:
        say("secrets: %s" % e)
        return 1
    for label, port, path in (("gateway", cfg.ports["admin"], "/_admin/health"),
                              ("dashboard", cfg.ports["dashboard"], "/health")):
        try:
            http("GET", "http://127.0.0.1:%d%s" % (port, path), token=tok, timeout=3)
            say("%-9s ok" % label)
        except Exception as e:  # noqa: BLE001
            say("%-9s UNREACHABLE (%s)" % (label, e))
            problems.append(label + " is unreachable")
    try:
        st = http("GET", "http://127.0.0.1:%d/state" % cfg.ports["fleet"], token=tok, timeout=3)
        prod, clones = st.get("prod") or {}, st.get("clones") or []
        say("prod      %s on release %s; clones %d/%s; gateway link %s" % (
            prod.get("active") or "NONE", prod.get("release"), len(clones), st.get("pool_size"),
            "ok" if st.get("gateway_ok") else "DOWN"))
        if not prod.get("active"):
            problems.append("no release in production")
        if len(clones) < int(st.get("pool_size") or 0):
            problems.append("clone pool below its size (%d/%s)" % (len(clones), st.get("pool_size")))
    except Exception as e:  # noqa: BLE001
        say("fleet     UNREACHABLE (%s)" % e)
        problems.append("fleet is unreachable")
    try:
        up = http("GET", "http://127.0.0.1:%d/_admin/upstream" % cfg.ports["admin"], token=tok, timeout=3)
        rules = http("GET", "http://127.0.0.1:%d/_admin/rules" % cfg.ports["admin"], token=tok, timeout=3)
        say("gateway   upstream %s (release %s), %d containment rule(s)" % (
            up.get("addr"), up.get("release"), len(rules.get("rules") or [])))
    except Exception:  # noqa: BLE001
        pass
    if problems:
        say("NOT HEALTHY: %s. `immune up` brings back what is missing without going back to t0." % "; ".join(problems))
        return 1
    say("healthy")
    return 0


def _events(cfg) -> list:
    out = []
    try:
        # the dashboard rotates the store to events.jsonl.1 (one generation): read it first, it is older
        for name in ("events.jsonl.1", "events.jsonl"):
            path = cfg.rt("bus", name)
            if name.endswith(".1") and not os.path.exists(path):
                continue
            with open(path, encoding="utf-8") as f:
                for line in f:
                    try:
                        e = json.loads(line)
                    except ValueError:
                        continue
                    if isinstance(e, dict):
                        out.append(e)
    except OSError:
        pass
    return out


def report(cfg: icfg.Config) -> dict:
    evs = _events(cfg)
    types = Counter(e.get("type") for e in evs)
    routed = [e.get("data") or {} for e in evs if e.get("type") == "request.routed"]
    verdicts = Counter(d.get("verdict") for d in routed if d.get("verdict"))
    routes = Counter(d.get("route") for d in routed)
    would = Counter(d.get("would_route") for d in routed if d.get("observe"))
    classes = Counter((e.get("data") or {}).get("class") for e in evs if e.get("type") == "request.classified")
    oracles = Counter()
    for e in evs:
        if e.get("type") == "oracle.fired":
            for x in (e.get("data") or {}).get("events") or []:
                oracles[x.get("oracle")] += 1
    incidents = {}
    for e in evs:
        d = e.get("data") or {}
        iid = d.get("incident") or e.get("incident")
        if not iid:
            continue
        inc = incidents.setdefault(iid, {"incident": iid})
        if e.get("type") == "incident.opened":
            inc.update({k: d.get(k) for k in ("vuln_class", "method", "route")})
            inc["origin"] = d.get("origin") or "live"
            if d.get("parent"):
                inc["parent"] = d["parent"]
        elif e.get("type") == "incident.closed":
            inc.update({k: d.get(k) for k in ("outcome", "outcome_detail", "seconds_to_rule", "seconds_to_patch")})
        elif e.get("type") == "verify.result":
            inc["exploit_blocked_on_prod"] = d.get("exploit_blocked_on_prod")
    from . import metrics
    det = metrics.detection(evs, metrics.load_recording(cfg.record_path))
    return {"project": cfg.name, "mode": cfg.mode, "events": len(evs), "requests": len(routed), "detection": det,
            "classes": dict(classes), "routes": dict(routes), "detonations": sum(verdicts.values()),
            "verdicts": dict(verdicts), "oracles": dict(oracles), "oracle_fired": types.get("oracle.fired", 0),
            "would_have": dict(would), "incidents": list(incidents.values())}


def metrics_lines(det: dict) -> list:
    from . import metrics
    return metrics.detection_lines(det)


def cmd_report(cfg: icfg.Config, as_json: bool) -> int:
    r = report(cfg)
    if as_json:
        say(json.dumps(r, indent=1))
        return 0
    say("project %s (mode %s): %d events, %d requests" % (r["project"], r["mode"], r["events"], r["requests"]))
    say("  classified: %s" % (", ".join("%s=%d" % kv for kv in sorted(r["classes"].items(), key=str)) or "-"))
    say("  routed:     %s" % (", ".join("%s=%d" % kv for kv in sorted(r["routes"].items(), key=str)) or "-"))
    say("  detonations: %d (%s)" % (r["detonations"], ", ".join("%s=%d" % kv for kv in r["verdicts"].items()) or "-"))
    say("  oracle.fired: %d (%s)" % (r["oracle_fired"], ", ".join("%s=%d" % kv for kv in r["oracles"].items()) or "-"))
    if r["would_have"]:
        say("  observe mode, enforce would have routed: %s" % ", ".join(
            "%s=%d" % kv for kv in sorted(r["would_have"].items(), key=str)))
        n = sum(v for k, v in r["would_have"].items() if k not in ("prod", None))
        say("  -> %d request(s) would have been denied or diverted to a shadow clone" % n)
    for line in metrics_lines(r["detection"]):
        say("  " + line)
    say("  incidents: %d" % len(r["incidents"]))
    for i in r["incidents"]:
        say("    %s %-5s %s %s %s -> %s%s (rule %ss, patch %ss)%s" % (
            i["incident"], i.get("origin") or "live", i.get("vuln_class"), i.get("method"), i.get("route"),
            i.get("outcome") or "open",
            "/" + i["outcome_detail"] if i.get("outcome_detail") else "", i.get("seconds_to_rule"),
            i.get("seconds_to_patch"),
            "" if i.get("exploit_blocked_on_prod") is None else " blocked_on_prod=%s" % i["exploit_blocked_on_prod"]))
    return 0


def cmd_set(cfg: icfg.Config, key: str, value: str) -> int:
    path = icfg.set_key(cfg.project_dir, key, value)
    say("%s: %s = %s" % (path, key, value))
    if key == "mode":
        try:
            tok = stack_secrets(cfg)["ADMIN_TOKEN"]
            http("POST", "http://127.0.0.1:%d/_admin/mode" % cfg.ports["admin"], {"mode": value}, tok, timeout=3)
            say("gateway switched to %s" % value)
        except (urllib.error.URLError, OSError, CliError) as e:
            say("gateway not reachable (%s); applies on the next `immune up`" % getattr(e, "reason", e))
    if key == "autopatch":
        eff, why = icfg.load(cfg.project_dir).effective_autopatch()
        if eff != value:
            say("effective autopatch: %s (%s)" % (eff, "; ".join(why)))
        say("the pipeline reads it at the start of each incident")
    return 0


def previous_release(cfg: icfg.Config, current: str) -> str | None:
    """The release built just before `current` (release directories by mtime); t0 when nothing else is left."""
    root = cfg.rt("releases")
    try:
        names = [n for n in os.listdir(root) if os.path.isdir(os.path.join(root, n))]
    except OSError:
        return None
    names.sort(key=lambda n: os.path.getmtime(os.path.join(root, n)))
    if current in names:
        older = names[:names.index(current)]
        return older[-1] if older else None
    others = [n for n in names if n != current]
    return others[-1] if others else None


def rules_to_restore(cfg: icfg.Config, target: str) -> list:
    """Rules of the patched incidents whose fix is not in `target`: the release chain (base_release -> release in
    <runtime>/pipeline/state.json) is walked back from `target`; an incident patched into a release outside that
    chain loses its fix with the rollback. A verified patch lifts its rule, so without this the rollback would
    reopen the defect with no containment."""
    try:
        with open(cfg.rt("pipeline", "state.json")) as f:
            incs = (json.load(f).get("incidents") or {})
    except (OSError, ValueError):
        return []
    parent = {i.get("release"): i.get("base_release") for i in incs.values()
              if isinstance(i, dict) and i.get("release") and i.get("base_release")}
    chain, r = set(), target
    while r and r not in chain:
        chain.add(r)
        r = parent.get(r)
    return [i["rule"] for i in incs.values()
            if isinstance(i, dict) and i.get("outcome") == "patched" and isinstance(i.get("rule"), dict)
            and i.get("release") and i["release"] not in chain]


def cmd_rollback(cfg: icfg.Config, to: str | None, keep_autopatch: bool) -> int:
    """Human override: put an earlier release back in production through the same blue/green path, and stop the
    pipeline from merging on its own (autopatch merge -> pr) unless --keep-autopatch. Active rules stay."""
    tok = stack_secrets(cfg)["ADMIN_TOKEN"]
    base = "http://127.0.0.1:%d" % cfg.ports["fleet"]
    try:
        st = http("GET", base + "/state", token=tok, timeout=5)
    except (urllib.error.URLError, OSError) as e:
        raise CliError("fleet not reachable (%s): is the stack up?" % getattr(e, "reason", e))
    current = str((st.get("prod") or {}).get("release") or "")
    target = to or previous_release(cfg, current)
    if not target:
        raise CliError("no earlier release than %r under %s; pass --to RELEASE" % (current, cfg.rt("releases")))
    if target == current:
        say("release %s is already in production" % current)
        return 0
    if not os.path.isdir(cfg.release_dir(target)):
        raise CliError("release %r not found under %s" % (target, cfg.rt("releases")))
    if not keep_autopatch and cfg.autopatch == "merge":
        cmd_set(cfg, "autopatch", "pr")
    say("rolling back production %s -> %s (blue/green, with health check and watch)" % (current, target))
    try:
        res = http("POST", base + "/deploy", {"release": target}, tok, timeout=600)
    except urllib.error.HTTPError as e:
        raise CliError("fleet refused the deploy: %s %s" % (e.code, e.read()[:300].decode("utf-8", "replace")))
    say(json.dumps(res))
    if not res.get("ok"):
        say("rollback did not complete; production stays on %s" % res.get("release"))
        return 1
    restored = []
    for rule in rules_to_restore(cfg, target):
        try:
            http("POST", "http://127.0.0.1:%d/_admin/rules" % cfg.ports["admin"], rule, tok, timeout=5)
            restored.append(rule.get("id") or "?")
        except (urllib.error.URLError, OSError) as e:
            say("could not re-activate %s (%s): that defect is open again without containment"
                % (rule.get("id"), getattr(e, "reason", e)))
    if restored:
        say("re-activated the containment rule(s) of the fixes this release lacks: %s" % ", ".join(restored))
    say("production on %s. `immune status` lists the active rules." % target)
    return 0


def dispatch(cmd: str, argv: list) -> int:
    if cmd == "anticipate":
        try:
            import runpy
            sys.argv = ["immune anticipate"] + argv
            runpy.run_module("anticipate", run_name="__main__", alter_sys=True)
            return 0
        except ModuleNotFoundError as e:
            if e.name == "anticipate":
                say("immune anticipate: not installed (package anticipate missing)")
                return 2
            raise
        except SystemExit as e:
            return int(e.code or 0) if not isinstance(e.code, str) else 1
    mod = DISPATCH[cmd]
    try:
        m = importlib.import_module(mod)
    except ModuleNotFoundError as e:
        if e.name == mod:
            say("immune %s: not installed (module %s is missing)" % (cmd, mod))
            return 2
        raise
    main = getattr(m, "main", None)
    if main is None:
        say("immune %s: not installed (%s has no main())" % (cmd, mod))
        return 2
    return int(main(argv) or 0)


def main(argv=None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    i = 0
    while i < len(argv) and argv[i].startswith("-"):   # skip leading options (and the value of --project)
        i += 2 if argv[i] == "--project" else 1
    if i < len(argv) and argv[i] in list(DISPATCH) + ["anticipate"]:
        return dispatch(argv[i], argv[:i] + argv[i + 1:])
    ap = argparse.ArgumentParser(prog="immune", description="immune: protect a web app (contracts/product.md)")
    ap.add_argument("--project", default=None, help="project dir (default: nearest .immune/ upward, else IMMUNE_HOME)")
    sub = ap.add_subparsers(dest="cmd", required=True)
    for c in ("up", "down", "status", "reset"):
        p = sub.add_parser(c)
        p.add_argument("--project", default=argparse.SUPPRESS)
    p = sub.add_parser("report")
    p.add_argument("--project", default=argparse.SUPPRESS)
    p.add_argument("--json", action="store_true")
    p = sub.add_parser("mode")
    p.add_argument("value", choices=icfg.MODES)
    p.add_argument("--project", default=argparse.SUPPRESS)
    p = sub.add_parser("autopatch")
    p.add_argument("value", choices=icfg.AUTOPATCH)
    p.add_argument("--project", default=argparse.SUPPRESS)
    p = sub.add_parser("rollback", help="put the previous release (or --to RELEASE) back in production")
    p.add_argument("--to", default=None, help="release to put back (default: the one built before the current one)")
    p.add_argument("--keep-autopatch", action="store_true", help="do not switch autopatch merge to pr")
    p.add_argument("--project", default=argparse.SUPPRESS)
    for c in list(DISPATCH) + ["anticipate"]:
        sub.add_parser(c, add_help=False)
    a = ap.parse_args(argv)
    project = a.project or os.environ.get("IMMUNE_PROJECT") or icfg.find_project()
    try:
        cfg = icfg.load(project)
        os.environ["IMMUNE_PROJECT"] = cfg.project_dir
        icfg.reset_cache()
        if a.cmd in ("up", "reset"):
            return cmd_up(cfg, reset=a.cmd == "reset")
        if a.cmd == "down":
            return cmd_down(cfg)
        if a.cmd == "status":
            return cmd_status(cfg)
        if a.cmd == "report":
            return cmd_report(cfg, a.json)
        if a.cmd in ("mode", "autopatch"):
            return cmd_set(cfg, a.cmd, a.value)
        if a.cmd == "rollback":
            return cmd_rollback(cfg, a.to, a.keep_autopatch)
    except icfg.ConfigError as e:
        print("immune: %s" % e, file=sys.stderr)
        return 2
    except CliError as e:
        print("immune %s: %s" % (a.cmd, e), file=sys.stderr)
        return 1
    return 2


if __name__ == "__main__":
    sys.exit(main())
